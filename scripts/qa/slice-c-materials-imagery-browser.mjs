// Usage: like slice-e-network-search-browser.mjs — local stack + vite dev server + ad-hoc playwright.
// SERVICE_KEY = local service key (fixture setup/teardown only). Never run against staging/production.
// Slice C browser QA against the REAL local backend (Auth + PostgREST + Storage). No interception.
import { chromium } from "playwright";
import { createClient } from "@supabase/supabase-js";
import fs from "node:fs";
const URL_ = "http://127.0.0.1:54321", APP = "http://127.0.0.1:5173";
const svc = createClient(URL_, process.env.SERVICE_KEY, { auth: { persistSession: false } });
const T = `qa${Date.now().toString(36)}`, PASSWORD = "Browser-QA-Pass-1", email = `${T}-editor@example.test`;
const results = []; const check = (n, ok, d = "") => { results.push(ok); console.log(`${ok ? "PASS" : "FAIL"} ${n}${d ? " — " + d : ""}`); };
const { data: u } = await svc.auth.admin.createUser({ email, password: PASSWORD, email_confirm: true, user_metadata: { display_name: `${T} Editor` } });
await svc.from("profiles").update({ onboarding_completed: true }).eq("id", u.user.id);
await svc.from("user_roles").insert({ user_id: u.user.id, role: "catalogue_editor", assignment_reason: "browser QA" });
// A real 64x48 PNG generated by the browser itself, so the image is genuine.
const browser = await chromium.launch(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {});
let materialId;
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = []; page.on("console", (m) => { if (m.type() === "error" && !m.text().includes("ERR_TUNNEL") && !m.location().url.endsWith("favicon.ico")) errors.push(m.text() + " @ " + m.location().url); });
  const png = Buffer.from((await page.evaluate(() => { const c = document.createElement("canvas"); c.width = 64; c.height = 48; const x = c.getContext("2d"); const g = x.createLinearGradient(0, 0, 64, 48); g.addColorStop(0, "#e9e4da"); g.addColorStop(1, "#8a7f70"); x.fillStyle = g; x.fillRect(0, 0, 64, 48); return c.toDataURL("image/png"); })).split(",")[1], "base64");
  fs.writeFileSync("./slab.png", png);
  await page.goto(`${APP}/auth`, { waitUntil: "networkidle" });
  await page.locator('input[type="email"]').fill(email);
  await page.locator('input[type="password"]').first().fill(PASSWORD);
  await page.getByRole("button", { name: "Sign in securely" }).click();
  await page.waitForTimeout(1500);
  await page.goto(`${APP}/catalogue`, { waitUntil: "networkidle" });
  check("editor reaches catalogue workspace", await page.getByText("Manage materials").isVisible());
  await page.getByLabel("Slug").fill(`${T}-calacatta`);
  await page.getByLabel("Name").fill(`${T} Calacatta`);
  await page.getByLabel(/Summary/).fill("Browser QA fixture summary.");
  await page.getByRole("button", { name: "Create draft" }).click();
  await page.waitForLoadState("networkidle"); await page.waitForTimeout(500);
  check("draft created and listed", await page.getByText(`${T} Calacatta`).first().isVisible());
  const { data: m } = await svc.from("materials").select("id").eq("slug", `${T}-calacatta`).single(); materialId = m.id;
  await page.setInputFiles('input[type="file"]', "./slab.png");
  await page.waitForLoadState("networkidle"); await page.waitForTimeout(800);
  const { data: row } = await svc.from("materials").select("image_path").eq("id", materialId).single();
  check("upload stored and row updated", /^materials\/.+\.png$/.test(row.image_path ?? ""), row.image_path);
  check("editor sees thumbnail + Replace/Remove", (await page.locator(`img[src*="${row.image_path}"]`).count()) === 1 && await page.getByText("Replace image").isVisible() && await page.getByRole("button", { name: "Remove image" }).isVisible());
  await page.getByRole("button", { name: "Publish" }).click();
  await page.waitForLoadState("networkidle"); await page.waitForTimeout(500);
  await page.screenshot({ path: "./slice-c-catalogue.png", fullPage: true });
  const guest = await browser.newPage({ viewport: { width: 390, height: 844 } });
  await guest.goto(`${APP}/materials/${T}-calacatta`, { waitUntil: "networkidle" });
  const hero = guest.locator(`img[alt="${T} Calacatta surface"]`);
  const loaded = await hero.evaluate((img) => img.complete && img.naturalWidth === 64).catch(() => false);
  check("guest detail page shows the real uploaded image", loaded);
  await guest.screenshot({ path: "./slice-c-detail.png", fullPage: true });
  await guest.goto(`${APP}/network`, { waitUntil: "networkidle" });
  await guest.getByRole("tab", { name: "Materials" }).click(); await guest.waitForLoadState("networkidle"); await guest.waitForTimeout(400);
  check("guest Network › Materials shows the thumbnail", (await guest.locator(`a[href="/materials/${T}-calacatta"] img`).count()) === 1);
  check("no horizontal overflow (guest)", !(await guest.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)));
  await page.getByRole("button", { name: "Remove image" }).click();
  await page.waitForLoadState("networkidle"); await page.waitForTimeout(800);
  const { data: after } = await svc.from("materials").select("image_path").eq("id", materialId).single();
  const gone = (await fetch(`${URL_}/storage/v1/object/public/materials-media/${row.image_path}`)).status;
  check("remove clears row and deletes the object", after.image_path === null && gone !== 200, `row=${after.image_path} object=${gone}`);
  await guest.goto(`${APP}/materials/${T}-calacatta`, { waitUntil: "networkidle" });
  check("guest page now shows no image and no placeholder", (await guest.locator("main img, img").count()) === 0);
  check("no console errors", errors.length === 0, errors.slice(0, 2).join(" | "));
} finally {
  await browser.close();
  if (materialId) { const { data: f } = await svc.storage.from("materials-media").list(`materials/${materialId}`); if (f?.length) await svc.storage.from("materials-media").remove(f.map((x) => `materials/${materialId}/${x.name}`)); await svc.from("materials").delete().eq("id", materialId); }
  await svc.from("user_roles").delete().eq("user_id", u.user.id); await svc.auth.admin.deleteUser(u.user.id);
}
const failed = results.filter((r) => !r).length; console.log(`\n${results.length - failed}/${results.length} browser checks passed`); process.exit(failed ? 1 : 0);
